package POJO;

public class CONDITIONS {

	private String NAME;
	private String KDATU;
	private double KBETR;
	private String KMEIN;
	private int KPEIN;

	public String getNAME() {
		return NAME;
	}

	public void setNAME(String NAME) {
		this.NAME = NAME;
	}

	public String getKDATU() {
		return KDATU;
	}

	public void setKDATU(String KDATU) {
		this.KDATU = KDATU;
	}

	public double getKBETR() {
		return KBETR;
	}

	public void setKBETR(double KBETR) {
		this.KBETR = KBETR;
	}

	public String getKMEIN() {
		return KMEIN;
	}

	public void setKMEIN(String KMEIN) {
		this.KMEIN = KMEIN;
	}

	public int getKPEIN() {
		return KPEIN;
	}

	public void setKPEIN(int KPEIN) {
		this.KPEIN = KPEIN;
	}
}
